"""Alembic environment. All modules' tables share one migration history.

Create a migration after changing models:
    alembic revision --autogenerate -m "dns: add blocklist tables"
"""

import asyncio

from alembic import context
from sqlalchemy.ext.asyncio import create_async_engine

from smp.core.config import get_settings
from smp.core.db import Base
from smp.modules import all_modules

all_modules()  # importing module packages registers their tables on Base.metadata

config = context.config
target_metadata = Base.metadata


def _url() -> str:
    return config.get_main_option("sqlalchemy.url") or get_settings().database_url


def run_offline() -> None:
    context.configure(url=_url(), target_metadata=target_metadata, literal_binds=True, compare_type=True)
    with context.begin_transaction():
        context.run_migrations()


def _do_run(connection) -> None:
    context.configure(connection=connection, target_metadata=target_metadata, compare_type=True)
    with context.begin_transaction():
        context.run_migrations()


async def run_online() -> None:
    engine = create_async_engine(_url())
    async with engine.connect() as conn:
        await conn.run_sync(_do_run)
    await engine.dispose()


if context.is_offline_mode():
    run_offline()
else:
    asyncio.run(run_online())
